/**
 * Builds the home locations map's background: public/map/region.svg (Saudi Arabia and the countries
 * around it) and src/content/map-geo.ts (projection constants and the country and sea labels).
 *
 * Source: Natural Earth 1:50m country boundaries (public domain), via the `world-atlas` package.
 * The projection is a Mercator fitted so Saudi Arabia fills the same box of the map's artboard as before.
 * Its constants are exported as PROJ so locations.ts can place each point from its longitude and latitude.
 *
 * Run: node scripts/build-map.mjs   (only needed if the fit or the list of labels changes)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoMercator, geoPath } from "d3-geo";

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));
const countries = feature(world, world.objects.countries).features;
const saudi = countries.find((c) => c.properties.name === "Saudi Arabia");

// Saudi Arabia's bounding box on the map's artboard (viewBox 370 90 1180 800).
const TARGET = [[503, 110], [1356, 836]];
// Everything drawn must cover the section at any screen size: the artboard plus a wide margin.
const CLIP = [[-700, -800], [3200, 1400]];

const projection = geoMercator().fitExtent(TARGET, saudi).clipExtent(CLIP);
const path = geoPath(projection);
// One decimal is enough at this size, and keeps the file small.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));
// Drop repeated points left by rounding.
const dedupe = (d) => d.replace(/([ML])(-?\d+,-?\d+)(?:L\2)+/g, "$1$2");

const [[cx0, cy0], [cx1, cy1]] = CLIP;
const neighbours = [];
for (const c of countries) {
  if (c === saudi) continue;
  const [[x0, y0], [x1, y1]] = path.bounds(c);
  if (!(x1 > cx0 && x0 < cx1 && y1 > cy0 && y0 < cy1)) continue;
  const d = path(c);
  if (d) neighbours.push(dedupe(round(d)));
}

// Country and sea names shown on the map: [name, longitude, latitude].
const LABELS = [
  ["Saudi Arabia", 44.6, 21.6], ["Jordan", 36.6, 30.9], ["Iraq", 43.4, 32.6], ["Kuwait", 47.5, 29.75], ["Iran", 55.5, 31.0],
  ["UAE", 54.5, 23.5], ["Oman", 56.6, 20.6], ["Yemen", 47.6, 15.5], ["Egypt", 30.4, 26.4],
  ["Sudan", 31.6, 17.6], ["Eritrea", 38.4, 15.6], ["Syria", 38.6, 35.2], ["Türkiye", 35.2, 38.9], ["Ethiopia", 39.6, 10.6],
  ["Pakistan", 66.5, 28.6], ["Afghanistan", 65.0, 33.6], ["Libya", 20.0, 27.0], ["Somalia", 47.4, 8.6], ["India", 76.0, 23.0],
  ["Turkmenistan", 59.0, 39.2],
];
const SEAS = [
  ["Red Sea", 37.9, 19.9], ["Arabian Gulf", 50.9, 28.75], ["Arabian Sea", 62.0, 16.0], ["Mediterranean Sea", 28.0, 33.9], ["Gulf of Aden", 48.0, 12.6],
];
const pt = ([name, lon, lat]) => {
  const [x, y] = projection([lon, lat]);
  return { name, x: Math.round(x), y: Math.round(y) };
};

const W = cx1 - cx0;
const H = cy1 - cy0;
// The drawing itself is a static file (kept out of the JavaScript bundle); the component lays it under the points.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${cx0} ${cy0} ${W} ${H}" width="${W}" height="${H}">
<defs><filter id="s" x="-10%" y="-10%" width="120%" height="120%"><feDropShadow dx="0" dy="6" stdDeviation="10" flood-color="#1c2a2a" flood-opacity="0.12"/></filter></defs>
<path d="${neighbours.join("")}" fill="#f1f3f2" stroke="#d3d8d7" stroke-width="1" stroke-linejoin="round"/>
<path d="${dedupe(round(path(saudi)))}" fill="#e1e6e4" stroke="#8f9997" stroke-width="1.25" stroke-linejoin="round" filter="url(#s)"/>
</svg>
`;
mkdirSync(new URL("../public/map/", import.meta.url), { recursive: true });
writeFileSync(new URL("../public/map/region.svg", import.meta.url), svg);

const out = `/* Generated by scripts/build-map.mjs from Natural Earth 1:50m (public domain). Do not edit by hand. */

/** Mercator constants: x = k·λ + tx, y = ty − k·ln(tan(π/4 + φ/2)), with λ and φ in radians. */
export const PROJ = ${JSON.stringify({ k: +projection.scale().toFixed(3), tx: +projection.translate()[0].toFixed(2), ty: +projection.translate()[1].toFixed(2) })};

/** The box public/map/region.svg covers, in the locations map's coordinates. */
export const REGION = ${JSON.stringify({ src: "/map/region.svg", x: cx0, y: cy0, width: W, height: H })};

export const COUNTRY_LABELS = ${JSON.stringify(LABELS.map(pt))};
export const SEA_LABELS = ${JSON.stringify(SEAS.map(pt))};
`;
writeFileSync(new URL("../src/content/map-geo.ts", import.meta.url), out);
console.log(`region.svg: ${(svg.length / 1024).toFixed(1)} KB, ${neighbours.length} neighbouring shapes`);
